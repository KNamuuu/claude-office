const assert = require('assert');
const vm = require('vm');
const fs = require('fs');
const context = vm.createContext({ window: {}, performance, console });
for (const file of ['layout.js', 'sprites.js', 'office.js']) vm.runInContext(fs.readFileSync(require('path').join(__dirname, '../renderer', file), 'utf8'), context);
const O = context.window.Office;
const base = { proj: 'P', sess: 'S', agent: 'main', src: 'codex' };
const send = e => O.ingest([{ ...base, ts: Date.now(), ...e }]);
send({ k: 'user', text: '로그인 수정' });
send({ k: 'tool', id: 'read', name: 'Read', summary: 'login.js' });
const f = O.floors.get('P'), c = f.chars.get('S/main');
assert.equal(O.taskTitle(f, c), '로그인 수정');
send({ k: 'title', text: '로그인 오류 해결' });
assert.equal(O.taskTitle(f, c), '로그인 오류 해결');
assert.equal(O.state(f, c).chip, '실행 중');
send({ k: 'result', id: 'read', error: true });
assert.equal(O.state(f, c).chip, '오류 확인');
assert.equal(f.log.at(-1).sess, 'S');
send({ k: 'user', text: '다시 해줘' });
send({ k: 'tool', id: 'ask', name: 'request_user_input', room: 'desk' });
assert.equal(O.state(f, c).chip, '입력 필요');
f.me.x += 5; O.tick(0.1);
assert.equal(c.room, 'follow');
f.me.x -= 5; O.tick(0.1);
assert.equal(c.room, 'desk');
send({ k: 'result', id: 'ask' });
send({ k: 'say', text: '중간 설명' });
assert.notEqual(O.state(f, c).chip, '응답 완료');
send({ k: 'complete' });
assert.equal(O.state(f, c).chip, '응답 완료');
send({ k: 'user', text: '다음 작업' });
assert.notEqual(O.state(f, c).chip, '응답 완료');
send({ k: 'tool', id: 'old', name: 'Bash', ts: Date.now() - 11 * 60000 });
assert.equal(O.state(f, c).chip, '상태 미확인');

// 서버에서 처음 받은 지난 기록(restore): 엘리베이터로 출근하지 않고 자리에 바로 앉는다. 표시 없으면 평소처럼 출근
const past = Date.now() - 60e3;
O.ingest([{ proj: 'R', sess: 'S', agent: 'main', src: 'claude', ts: past, k: 'tool', id: 'r1', name: 'Bash', summary: 'ls', restore: true }]);
const rf = O.floors.get('R'), rc = rf.chars.get('S/main');
assert.ok(!rc.gone && rc.elevator === undefined && rf.elevators.every(t => t === 0), 'restore: 엘리베이터 없이 배치');
assert.equal(rc.room, 'server');
O.ingest([{ proj: 'L', sess: 'S', agent: 'main', src: 'claude', ts: Date.now(), k: 'tool', id: 'l1', name: 'Bash', summary: 'ls' }]);
assert.ok(O.floors.get('L').chars.get('S/main').elevator !== undefined, '평소: 엘리베이터로 출근');
console.log('office-state-check OK');
